#!/usr/bin/env nix-shell
#!nix-shell -i python3 -p "python3.withPackages (p: [ p.fonttools p.brotli ])"
"""Writes the web fonts in static/webfonts/ and the icon classes in assets/sass/base/_icons.scss.

Text fonts are Latin subsets of Source Sans Pro and Raleway from nixpkgs, in the weights the
stylesheet uses. The icon font is cut down from design/nerd-fonts/ to the icons named in data/, so
rerun this after adding an icon there.
"""
import re
import subprocess
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "static" / "webfonts"
NERD = ROOT / "design" / "nerd-fonts"

LATIN = "U+0020-007E,U+00A0-017F,U+2010-2027,U+2030,U+2039-203A,U+20AC,U+2122,U+2190-2193,U+2212"

# package, file in share/fonts/truetype, output name
TEXT = [
    ("source-sans-pro", "SourceSansPro-Light.ttf", "source-sans-300"),
    ("source-sans-pro", "SourceSansPro-LightIt.ttf", "source-sans-300-italic"),
    ("source-sans-pro", "SourceSansPro-Semibold.ttf", "source-sans-600"),
    ("source-sans-pro", "SourceSansPro-Bold.ttf", "source-sans-700"),
    ("raleway", "Raleway-SemiBold.ttf", "raleway-600"),
    ("raleway", "Raleway-ExtraBold.ttf", "raleway-800"),
]

# Used by the stylesheet itself (the checkbox tick in components/_form.scss).
EXTRA_ICONS = ["fa-check"]


def woff2(source, unicodes, name):
    subset.main([str(source), f"--unicodes={unicodes}", "--flavor=woff2", f"--output-file={OUT / name}.woff2"])


def package(name):
    out = subprocess.run(["nix-build", "<nixpkgs>", "-A", name, "--no-out-link"], check=True, capture_output=True, text=True)
    return Path(out.stdout.strip()) / "share" / "fonts" / "truetype"


OUT.mkdir(parents=True, exist_ok=True)
paths = {}
for pkg, file, name in TEXT:
    paths.setdefault(pkg, package(pkg))
    woff2(paths[pkg] / file, LATIN, name)

icons = sorted({m for f in (ROOT / "data").rglob("*.yml") for m in re.findall(r"^icon:\s*(\S+)", f.read_text(), re.M)} | set(EXTRA_ICONS))
codes = dict(re.findall(r'^\.nf-(\S+):before \{\s*content: "\\(\w+)";', (NERD / "nerd-fonts-generated.css").read_text(), re.M))
missing = [i for i in icons if i not in codes]
if missing:
    raise SystemExit(f"not in the icon font: {', '.join(missing)}")

woff2(NERD / "nf-regular-2048.ttf", ",".join(f"U+{codes[i]}" for i in icons), "icons")
rules = "".join(f'\t.nf-{i}:before {{\n\t\tcontent: "\\{codes[i]}";\n\t}}\n\n' for i in icons)
(ROOT / "assets" / "sass" / "base" / "_icons.scss").write_text(
    "/* Icons (Nerd Fonts 2.0.0); generated by design/subset-fonts.py */\n\n" + rules.rstrip("\n") + "\n"
)
